using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.Json;
using CollectorsAnxiety.Base;
using Dalamud.Plugin.Services;

namespace CollectorsAnxiety.Data;

public class ItemSource
{
    public string Type { get; init; } = "";
    public string Text { get; init; } = "";
    public string? Detail { get; init; }

    /// <summary>
    /// Set when the source text is an English fallback, as no Traditional Chinese data exists for the entry.
    /// </summary>
    public bool English { get; init; }
}

internal class ItemSourceDocument
{
    public string? GeneratedAt { get; init; }
    public string? TcDataExportedAt { get; init; }
    public Dictionary<string, Dictionary<uint, List<ItemSource>>> Sources { get; init; } = new();
}

/// <summary>
/// Provides Traditional Chinese item acquisition sources, generated by tools/generate_item_sources.py.
/// </summary>
public class ItemSources
{
    private const string ResourceName = "CollectorsAnxiety.Resources.ItemSourcesTC.json";
    private const string ItemCategory = "Item";

    // Traditional Chinese server world IDs, as listed by Universalis (data center 陸行鳥, worlds 4028-4035). CN worlds
    // use 1xxx and KR worlds 2xxx, so treat the whole 4xxx block as TC to pick up any future worlds.
    private const uint TcWorldIdMin = 4000;
    private const uint TcWorldIdMax = 4999;

    private readonly IPluginLog _pluginLog;
    private readonly IClientState _clientState;
    private readonly PluginConfig _pluginConfig;
    private readonly Lazy<ItemSourceDocument> _document;
    private readonly Dictionary<(Type, uint), string?> _tooltipCache = new();

    public ItemSources(IPluginLog pluginLog, IClientState clientState, PluginConfig pluginConfig)
    {
        _pluginLog = pluginLog;
        _clientState = clientState;
        _pluginConfig = pluginConfig;
        _document = new Lazy<ItemSourceDocument>(Load);
    }

    public bool IsEnabled => _pluginConfig.ItemSourceMode switch
    {
        ItemSourceMode.Always => true,
        ItemSourceMode.Never => false,
        _ => IsTraditionalChineseClient(),
    };

    /// <summary>
    /// Best-effort detection of the Traditional Chinese client. The upstream ClientLanguage enum has no TC value, so
    /// check its name (in case a TC Dalamud build adds one) and fall back to the player's home world.
    /// </summary>
    public bool IsTraditionalChineseClient()
    {
        var language = _clientState.ClientLanguage.ToString();
        if (language.Contains("Traditional", StringComparison.OrdinalIgnoreCase) ||
            language.Contains("TW", StringComparison.Ordinal))
        {
            return true;
        }

        var homeWorld = _clientState.LocalPlayer?.HomeWorld.RowId;
        return homeWorld is >= TcWorldIdMin and <= TcWorldIdMax;
    }

    public string? DataTimestamp => _document.Value.TcDataExportedAt ?? _document.Value.GeneratedAt;

    public IReadOnlyList<ItemSource> GetSources<T>(Unlockable<T> entry) where T : struct, Lumina.Excel.IExcelRow<T>
    {
        var sources = _document.Value.Sources;

        if (entry.SourceCategory != null && sources.TryGetValue(entry.SourceCategory, out var category))
        {
            var found = entry.SourceIds
                .SelectMany(id => category.TryGetValue(id, out var list) ? list : [])
                .ToList();

            if (found.Count > 0)
            {
                return found;
            }
        }

        if (entry.UnlockItem is { } unlockItem &&
            sources.TryGetValue(ItemCategory, out var items) &&
            items.TryGetValue(unlockItem.RowId, out var itemSources))
        {
            return itemSources;
        }

        return [];
    }

    /// <summary>
    /// Gets the formatted source tooltip for an entry, or null if no sources are known.
    /// </summary>
    public string? GetTooltip<T>(Unlockable<T> entry) where T : struct, Lumina.Excel.IExcelRow<T>
    {
        var key = (entry.GetType(), entry.Id);
        if (!_tooltipCache.TryGetValue(key, out var tooltip))
        {
            var sources = GetSources(entry);
            tooltip = _tooltipCache[key] = sources.Count > 0 ? FormatTooltip(sources) : null;
        }

        return tooltip;
    }

    public static string FormatTooltip(IReadOnlyList<ItemSource> sources)
    {
        var sb = new StringBuilder("取得方式：");
        foreach (var source in sources)
        {
            sb.Append($"\n• [{source.Type}] {source.Text}");
            if (source.Detail != null)
            {
                sb.Append($"\n    {source.Detail}");
            }
        }

        if (sources.Any(s => s.English))
        {
            sb.Append("\n\n（暫無繁體中文資料，以上為 FFXIV Collect 的英文資料）");
        }

        return sb.ToString();
    }

    private ItemSourceDocument Load()
    {
        try
        {
            using var stream = typeof(ItemSources).Assembly.GetManifestResourceStream(ResourceName)
                               ?? throw new InvalidOperationException($"Missing embedded resource {ResourceName}");
            var document = JsonSerializer.Deserialize<ItemSourceDocument>(stream) ?? new ItemSourceDocument();

            _pluginLog.Debug($"Loaded item sources for {document.Sources.Sum(c => c.Value.Count)} entries " +
                             $"(data from {document.TcDataExportedAt})");
            return document;
        }
        catch (Exception ex)
        {
            _pluginLog.Error(ex, "Failed to load item sources");
            return new ItemSourceDocument();
        }
    }
}
